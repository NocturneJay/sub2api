-- 渠道监控探测标记：把健康检查产生的用量记录与用户真实用量区分开，
-- 供管理端「使用记录」按需排除。
--
-- 编号说明：aicat 自研迁移从 900 起单独编号，不再插进上游序列。
-- 上游正在 192/193 一带持续新增迁移，沿用相邻编号迟早撞车（现有的
-- 154/159/187 三个自研迁移混在上游序列里，至今没出事只是运气好）。
-- 本类迁移都是纯新增列，按文件名排序落在最后执行没有任何影响。
--
-- 只加列、不动既有数据：存量记录一律为 FALSE，即「不是监控探测」。
-- 这与产品口径一致——标记只对上线后新产生的记录生效，历史记录不回填，
-- 因为事后无法可靠地把监控请求从真实请求里认出来（监控与管理员真实使用
-- 共用同一把 API 密钥，UA 也可能被管理员配成与真实客户端一致）。
--
-- 不建索引：管理端的排除条件是 is_channel_monitor 为假，几乎匹配全表，
-- 索引对它没有帮助；只有「只看监控记录」这种反向查询才用得上，而那不是
-- 当前需求。usage_logs 是计费写入路径上的大表（部署时约 63 万行 / 707 MB），
-- 建一个用不上的索引反而要付出一次阻塞写入的构建代价。
--
-- PostgreSQL 11 起，带非易变默认值的 ADD COLUMN 是元数据操作，不重写表，
-- 因此本迁移在大表上也是瞬时完成的。
ALTER TABLE usage_logs
    ADD COLUMN IF NOT EXISTS is_channel_monitor BOOLEAN NOT NULL DEFAULT FALSE;
